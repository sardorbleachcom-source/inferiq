const root = document.documentElement;
const languageSelect = document.getElementById("languageSelect");
const themeToggle = document.getElementById("themeToggle");
const themeIcon = document.getElementById("themeIcon");
const menuToggle = document.getElementById("menuToggle");
const nav = document.querySelector(".desktop-nav");

function applyLanguage(lang) {
  const dictionary = translations[lang] || translations.uz;
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (dictionary[key] !== undefined) element.innerHTML = dictionary[key];
  });
  languageSelect.value = lang;
  localStorage.setItem("inferiq-language", lang);
}
function applyTheme(theme) {
  root.dataset.theme = theme;
  themeIcon.textContent = theme === "dark" ? "☼" : "☾";
  themeToggle.setAttribute("aria-label", theme === "dark" ? "Switch to light mode" : "Switch to dark mode");
  document.querySelector('meta[name="theme-color"]').content = theme === "dark" ? "#080b16" : "#eef2fb";
  localStorage.setItem("inferiq-theme", theme);
}
languageSelect.addEventListener("change", (event) => applyLanguage(event.target.value));
themeToggle.addEventListener("click", () => applyTheme(root.dataset.theme === "dark" ? "light" : "dark"));
menuToggle.addEventListener("click", () => {
  const opened = nav.classList.toggle("open");
  menuToggle.textContent = opened ? "×" : "☰";
  menuToggle.setAttribute("aria-expanded", String(opened));
});
nav.querySelectorAll("a").forEach((link) => link.addEventListener("click", () => {
  nav.classList.remove("open");
  menuToggle.textContent = "☰";
  menuToggle.setAttribute("aria-expanded", "false");
}));

applyLanguage(localStorage.getItem("inferiq-language") || "uz");
applyTheme(localStorage.getItem("inferiq-theme") || (window.matchMedia("(prefers-color-scheme: light)").matches ? "light" : "dark"));

const revealObserver = new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    if (entry.isIntersecting) {
      entry.target.classList.add("visible");
      revealObserver.unobserve(entry.target);
    }
  });
}, { threshold: 0.12 });
document.querySelectorAll(".reveal").forEach((element) => revealObserver.observe(element));

// A restrained cursor-following highlight for Liquid Glass panels.
document.querySelectorAll(".service-card, .project-card, .contact-panel, .core-card").forEach((panel) => {
  panel.addEventListener("pointermove", (event) => {
    const rect = panel.getBoundingClientRect();
    panel.style.setProperty("--pointer-x", `${event.clientX - rect.left}px`);
    panel.style.setProperty("--pointer-y", `${event.clientY - rect.top}px`);
  });
});
